function Date.__get:weekday()
    local p, leap, a, b

    p    = private[self]
    leap = isLeapYear(p.year)
    
    a = p.year % 100
    b = (p.year - a) / 100
    
    return ((a + math.floor(a / 4) - 2 * b + p.day + math.floor(b / 4) + months_lut[p.month] - (p.month >= 3 and 0 or leap and 2 or 1)) % 7) + 1
end

